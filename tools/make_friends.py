S = 'stroke="#111" stroke-width="7" stroke-linejoin="round" stroke-linecap="round"'

def el(tag, fill='#fff', extra='', **a):
    attrs = ' '.join(f'{k.replace("_","-")}="{v}"' for k, v in a.items())
    return f'<{tag} {attrs} fill="{fill}" {S} {extra}/>'
def ell(cx, cy, rx, ry, rot=0, fill='#fff'):
    t = f'transform="rotate({rot} {cx} {cy})"' if rot else ''
    return el('ellipse', fill, t, cx=cx, cy=cy, rx=rx, ry=ry)
def circ(cx, cy, r, fill='#fff'): return el('circle', fill, '', cx=cx, cy=cy, r=r)
def path(d, fill='#fff'): return el('path', fill, '', d=d)
def line(d): return f'<path d="{d}" fill="none" {S}/>'
def rect(x, y, w, h, rx=0, fill='#fff'): return el('rect', fill, '', x=x, y=y, width=w, height=h, rx=rx)
def eye(cx, cy, r=20):
    return circ(cx, cy, r) + circ(cx + r*0.2, cy + r*0.1, r*0.5, '#111') + f'<circle cx="{cx+r*0.35}" cy="{cy-r*0.15}" r="{r*0.18}" fill="#fff"/>'
def poly(pts, fill='#fff'): return el('polygon', fill, '', points=' '.join(f'{x},{y}' for x, y in pts))

def svg(body): return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 700 700" width="700" height="700"><rect width="700" height="700" fill="#fff"/>{body}</svg>'

